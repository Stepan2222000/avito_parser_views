-- Вьюхи для отчётов. Живут в базе библиотеки, потому что там лежит всё нужное: и
-- находки по запросам, и наблюдения за просмотрами. Мы ничего не дублируем, а только
-- достаём артикул из ключа запроса — библиотека кладёт его туда как «?q=<артикул>».

create or replace view артикулы_объявления as
select split_part(з.ключ, 'q=', 2) as артикул,
       н.объявление,
       н.страница,
       н.впервые,
       н.последний_раз
from находки н
join запросы з on з.номер = н.запрос
where з.ключ like '%?q=%';

comment on view артикулы_объявления is
    'Связь артикула с объявлениями: артикул достаётся из ключа запроса';

-- Просмотры по артикулу и дню: сумма по всем объявлениям, найденным по этому артикулу.
-- За день берётся последнее наблюдение по каждому объявлению — визитов в день может быть
-- несколько, и складывать их было бы двойным счётом.
create or replace view просмотры_по_артикулам as
with за_день as (
    select distinct on (н.объявление, (н.когда at time zone 'UTC')::date)
           н.объявление,
           (н.когда at time zone 'UTC')::date as день,
           н.просмотров_всего,
           н.просмотров_сегодня,
           н.цена
    from наблюдения н
    where н.просмотров_всего is not null
    order by н.объявление, (н.когда at time zone 'UTC')::date, н.когда desc
)
select а.артикул,
       д.день,
       count(*) as объявлений,
       sum(д.просмотров_всего) as просмотров_всего,
       sum(д.просмотров_сегодня) as просмотров_сегодня,
       avg(д.цена)::bigint as цена_средняя
from за_день д
join артикулы_объявления а on а.объявление = д.объявление
group by а.артикул, д.день;

comment on view просмотры_по_артикулам is
    'Артикул, день, сколько объявлений и сколько у них просмотров; за день берётся '
    'последнее наблюдение по каждому объявлению';

-- То же, но только по объявлениям, где артикул действительно упомянут в тексте. Авито
-- по номеру с дефисом отдаёт и постороннее: по «09-812» находится 1900 объявлений, и в
-- сумме просмотров они перевешивают настоящий спрос. Здесь такого нет — зато нет и
-- объявлений, где номер указан иначе, чем в базе.
create or replace view просмотры_по_артикулам_точные as
with за_день as (
    select distinct on (н.объявление, (н.когда at time zone 'UTC')::date)
           н.объявление,
           (н.когда at time zone 'UTC')::date as день,
           н.просмотров_всего,
           н.просмотров_сегодня,
           н.цена
    from наблюдения н
    where н.просмотров_всего is not null
    order by н.объявление, (н.когда at time zone 'UTC')::date, н.когда desc
)
select а.артикул,
       д.день,
       count(*) as объявлений,
       sum(д.просмотров_всего) as просмотров_всего,
       sum(д.просмотров_сегодня) as просмотров_сегодня,
       avg(д.цена)::bigint as цена_средняя
from за_день д
join артикулы_объявления а on а.объявление = д.объявление
join объявления о on о.номер = д.объявление
where о.заголовок ilike '%' || а.артикул || '%'
   or coalesce(о.описание, '') ilike '%' || а.артикул || '%'
   or coalesce(о.выжимка, '') ilike '%' || а.артикул || '%'
group by а.артикул, д.день;

comment on view просмотры_по_артикулам_точные is
    'Как просмотры_по_артикулам, но только объявления, в тексте которых артикул есть';
