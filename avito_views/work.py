"""Обход: одинаковые воркеры, каждый берёт задачу любого типа.

Воркер — это один экземпляр `Авито`, а значит один адрес, пока тот жив. Задачи он берёт
из общей очереди: каталог артикула или карточка объявления. Пока карточек в очереди
меньше порога, воркеры разбирают артикулы; как только накопилось — переключаются на
карточки. Так очередь держится около порога, и оба вида работы идут вперемешку.

Страницы выдачи берём по одной: у Авито нельзя просить страницу, которой нет — задача
падает целиком, а сколько их всего, известно только с первой страницы.
"""
from __future__ import annotations

import asyncio
import logging
from urllib.parse import quote

from avito import Авито, Store
from avito.errors import (АдресаКончились, НеопознаннаяСтраница, ОбъявлениеСнято)

from avito_views.config import Настройки
from avito_views.db import Очередь, ЗадачаАртикул, ЗадачаКарточка
from avito_views.log import Наблюдатель
from avito_views.proxies import Поставщик

лог = logging.getLogger("обход")

# Глубже сотой страницы Авито не пускает: это около пяти тысяч объявлений на любую
# выдачу. Если упёрлись, знать об этом важнее, чем молча собрать часть.
ПОТОЛОК_СТРАНИЦ = 100
НА_СТРАНИЦЕ = 50


class Счёт:
    """Что успели за прогон — для итоговой строки в журнале."""

    def __init__(self, предел: int | None = None):
        self.артикулов = 0
        self.карточек = 0
        self.снятых = 0
        self.ошибок = 0
        self.объявлений = 0
        self.новых = 0
        self.предел = предел

    def можно_ещё(self) -> bool:
        if self.предел is None:
            return True
        return self.артикулов + self.карточек + self.снятых + self.ошибок < self.предел

    def строкой(self) -> str:
        return (f"артикулов {self.артикулов}, карточек {self.карточек}, "
                f"снятых {self.снятых}, ошибок {self.ошибок}, "
                f"объявлений найдено {self.объявлений} (новых {self.новых})")


async def обойти(настройки: Настройки, *, предел: int | None = None,
                 воркеров: int | None = None) -> Счёт:
    """Запустить пул воркеров, пока в очереди есть задачи."""
    поставщик = Поставщик(настройки.прокси, остывание=настройки.остывание,
                          предел=настройки.остывание_предел,
                          молчание=настройки.молчание)
    if not len(поставщик):
        raise SystemExit(f"в файле {настройки.прокси} нет ни одного адреса")

    сколько = воркеров or настройки.воркеров
    сколько = min(сколько, len(поставщик))
    очередь = Очередь(настройки.очередь_dsn, размер=min(сколько, 20) + 4)
    склад = Store(настройки.склад_dsn)
    счёт = Счёт(предел)
    стоп = asyncio.Event()

    лог.info("адресов %d, воркеров %d, порог карточек %d, предел страниц %d",
             len(поставщик), сколько, настройки.порог_карточек, настройки.страниц)
    брошено = await очередь.сбросить_зависшие(настройки.зависла_через)
    if брошено["артикулов"] or брошено["карточек"]:
        лог.info("возвращено брошенных задач: %s", брошено)

    try:
        await asyncio.gather(*(_воркер(н, поставщик, очередь, склад, настройки, счёт, стоп)
                               for н in range(сколько)))
    finally:
        лог.info("итог: %s", счёт.строкой())
        лог.info("адреса: %s", поставщик.сводка())
        await поставщик.закрыть()
        await склад.close()
        await очередь.закрыть()
    return счёт


async def _воркер(номер: int, поставщик: Поставщик, очередь: Очередь, склад: Store,
                  настройки: Настройки, счёт: Счёт, стоп: asyncio.Event) -> None:
    наблюдатель = Наблюдатель(f"воркер-{номер:02d}")
    авито = Авито(поставщик, склад=склад, наблюдатель=наблюдатель)
    while not стоп.is_set() and счёт.можно_ещё():
        задача = await очередь.взять_задачу(порог=настройки.порог_карточек)
        if задача is None:
            return
        try:
            if isinstance(задача, ЗадачаАртикул):
                await _каталог(авито, очередь, задача, настройки, счёт)
            else:
                await _карточка(авито, очередь, склад, задача, настройки, счёт)
        except АдресаКончились as e:
            лог.error("адреса кончились, останавливаемся: %s", e)
            await _вернуть(очередь, задача)
            стоп.set()
            return
        except asyncio.CancelledError:
            await _вернуть(очередь, задача)
            raise


async def _каталог(авито: Авито, очередь: Очередь, задача: ЗадачаАртикул,
                   настройки: Настройки, счёт: Счёт) -> None:
    ссылка = f"{задача.путь}?q={quote(задача.артикул)}"
    try:
        первая = await авито.каталог(ссылка, страниц=1)
    except АдресаКончились:
        raise
    except Exception as e:  # noqa: BLE001 — исход задачи, не обхода
        await _артикул_упал(очередь, задача, e, настройки, счёт)
        return

    страниц_всего = первая.страниц_всего or 1
    докуда = min(страниц_всего, настройки.страниц, ПОТОЛОК_СТРАНИЦ)
    найденные = [(int(о["item_id"]), 1) for о in первая.объявления]
    заметка = None

    for страница in range(2, докуда + 1):
        try:
            ещё = await авито.каталог(ссылка, с_какой=страница, страниц=1)
        except АдресаКончились:
            raise
        except НеопознаннаяСтраница:
            # Авито завышает число страниц: обещанная страница просто не открывается.
            # Всё, что было до неё, собрано, поэтому это конец выдачи, а не поломка.
            заметка = (f"выдача кончилась на странице {страница}, "
                       f"хотя обещали {страниц_всего}")
            лог.info("артикул %s: %s", задача.артикул, заметка)
            break
        except Exception as e:  # noqa: BLE001 — исход задачи, не обхода
            await _артикул_упал(очередь, задача, e, настройки, счёт)
            return
        найденные += [(int(о["item_id"]), страница) for о in ещё.объявления]
        if len(ещё.объявления) < НА_СТРАНИЦЕ:
            break               # страница неполная — дальше пусто

    новых = await очередь.поставить_объявления(задача.артикул, найденные)
    широкий = страниц_всего >= ПОТОЛОК_СТРАНИЦ
    await очередь.артикул_готов(задача.артикул, всего=первая.всего,
                               страниц=страниц_всего, объявлений=len(найденные),
                               широкий=широкий, заметка=заметка)
    счёт.артикулов += 1
    счёт.объявлений += len(найденные)
    счёт.новых += новых
    лог.info("артикул %s: найдено %s, собрано %d (новых %d), страниц %d%s",
             задача.артикул, первая.всего, len(найденные), новых, докуда,
             ", упёрлись в потолок" if широкий else "")


async def _карточка(авито: Авито, очередь: Очередь, склад: Store,
                    задача: ЗадачаКарточка, настройки: Настройки, счёт: Счёт) -> None:
    try:
        итог = await авито.карточки([задача.номер])
    except ОбъявлениеСнято:
        await склад.mark_removed(задача.номер)
        await очередь.карточка_снята(задача.номер)
        счёт.снятых += 1
        return
    except АдресаКончились:
        raise
    except Exception as e:  # noqa: BLE001 — исход задачи, не обхода
        статус = await очередь.карточка_упала(задача.номер, f"{type(e).__name__}: {e}",
                                              попыток=настройки.попыток)
        счёт.ошибок += 1
        лог.warning("карточка %s: %s — %s (статус %s)", задача.номер,
                    type(e).__name__, str(e)[:120], статус)
        return

    карточка = итог.карточки[0]
    await очередь.карточка_готова(задача.номер, карточка.get("views_total"))
    счёт.карточек += 1


async def _артикул_упал(очередь: Очередь, задача: ЗадачаАртикул, ошибка: Exception,
                        настройки: Настройки, счёт: Счёт) -> None:
    статус = await очередь.артикул_упал(задача.артикул,
                                        f"{type(ошибка).__name__}: {ошибка}",
                                        попыток=настройки.попыток)
    счёт.ошибок += 1
    лог.warning("артикул %s: %s — %s (статус %s)", задача.артикул,
                type(ошибка).__name__, str(ошибка)[:120], статус)


async def _вернуть(очередь: Очередь, задача) -> None:
    if isinstance(задача, ЗадачаАртикул):
        await очередь.артикул_вернуть(задача.артикул)
    elif isinstance(задача, ЗадачаКарточка):
        await очередь.карточку_вернуть(задача.номер)
