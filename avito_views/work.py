"""Обход выдачи: артикул за артикулом, страница за страницей.

Воркер — это один экземпляр `Авито`, а значит один адрес, пока тот жив: библиотека
возвращает адрес только когда с ним не сложилось. Поэтому воркеров держим меньше, чем
адресов, иначе замены не найдётся и пул встанет в ожидание.

Страницы берём по одной. Просить страницу, которой нет, нельзя — задача падает целиком, а
сколько их всего, известно только с первой. Листаем по дате: выдача во время обхода
сдвигается, и при сортировке по дате новые объявления толкают её вниз, так что мы получаем
повторы (они бесплатны, номера всё равно дедуплицируются), а не пропуски.

Карточки этот этап не разбирает: он только находит объявления и ставит их в очередь.
"""
from __future__ import annotations

import asyncio
import logging
from urllib.parse import quote

from avito import Авито, Склад
from avito.errors import АдресаКончились, НеопознаннаяСтраница

from avito_views.config import Настройки
from avito_views.db import Очередь, ЗадачаАртикул
from avito_views.log import Наблюдатель
from avito_views.proxies import Поставщик

лог = logging.getLogger("обход")

# Глубже сотой страницы Авито не пускает: это около пяти тысяч объявлений на любую
# выдачу. Если упёрлись, знать об этом важнее, чем молча собрать часть.
ПОТОЛОК_СТРАНИЦ = 100
НА_СТРАНИЦЕ = 50


class Счёт:
    """Что успели за прогон — для итоговой строки в журнале."""

    def __init__(self, предел: int | None = None):
        self.артикулов = 0
        self.пустых = 0
        self.ошибок = 0
        self.объявлений = 0
        self.новых = 0
        self.предел = предел

    def сделано(self) -> int:
        return self.артикулов + self.пустых + self.ошибок

    def можно_ещё(self) -> bool:
        return self.предел is None or self.сделано() < self.предел

    def строкой(self) -> str:
        return (f"артикулов {self.артикулов}, пустых {self.пустых}, "
                f"ошибок {self.ошибок}, объявлений найдено {self.объявлений} "
                f"(новых {self.новых})")


async def обойти(настройки: Настройки, *, предел: int | None = None,
                 воркеров: int | None = None) -> Счёт:
    """Обойти выдачи по артикулам, пока в очереди есть задачи."""
    поставщик = Поставщик(настройки.прокси, остывание=настройки.остывание,
                          проба=настройки.проба, молчание=настройки.молчание)
    if not len(поставщик):
        raise SystemExit(f"в файле {настройки.прокси} нет ни одного адреса")

    сколько = min(воркеров or настройки.воркеров, len(поставщик))
    очередь = Очередь(настройки.очередь_dsn, размер=min(сколько, 20) + 4)
    склад = Склад(настройки.склад_dsn)
    счёт = Счёт(предел)
    стоп = asyncio.Event()

    лог.info("адресов %d, воркеров %d, предел страниц %d, сортировка %s",
             len(поставщик), сколько, настройки.страниц,
             настройки.сортировка or "как отдаёт Авито")
    брошено = await очередь.сбросить_зависшие(настройки.зависла_через)
    if брошено:
        лог.info("возвращено брошенных задач: %d", брошено)

    try:
        await asyncio.gather(*(_воркер(н, поставщик, очередь, склад, настройки, счёт, стоп)
                               for н in range(сколько)))
    finally:
        лог.info("итог: %s", счёт.строкой())
        лог.info("адреса: %s", поставщик.сводка())
        await поставщик.закрыть()
        await склад.закрыть()
        await очередь.закрыть()
    return счёт


async def _воркер(номер: int, поставщик: Поставщик, очередь: Очередь, склад: Склад,
                  настройки: Настройки, счёт: Счёт, стоп: asyncio.Event) -> None:
    наблюдатель = Наблюдатель(f"воркер-{номер:02d}", настройки.дампы)
    авито = Авито(поставщик, склад=склад, наблюдатель=наблюдатель)
    while not стоп.is_set() and счёт.можно_ещё():
        задача = await очередь.взять_артикул()
        if задача is None:
            return
        try:
            await _выдача(авито, очередь, задача, настройки, счёт, наблюдатель)
        except АдресаКончились as e:
            лог.error("адреса кончились, останавливаемся: %s", e)
            await очередь.артикул_вернуть(задача.артикул)
            стоп.set()
            return
        except asyncio.CancelledError:
            await очередь.артикул_вернуть(задача.артикул)
            raise
        except Exception as e:  # noqa: BLE001 — падение задачи не должно валить обход
            лог.exception("воркер %d: задача сорвалась на %s", номер, type(e).__name__)
            await очередь.артикул_вернуть(задача.артикул)
            счёт.ошибок += 1


async def _выдача(авито: Авито, очередь: Очередь, задача: ЗадачаАртикул,
                  настройки: Настройки, счёт: Счёт, наблюдатель: Наблюдатель) -> None:
    ссылка = f"{задача.путь}?q={quote(задача.артикул)}"
    порядок = настройки.сортировка

    try:
        первая = await авито.каталог(ссылка, сортировка=порядок, страниц=1)
    except АдресаКончились:
        raise
    except НеопознаннаяСтраница as e:
        # По номерам, которых на Авито нет вовсе, приходит страница подбора по артикулу:
        # разметка есть, данных нет. Проверено — соседняя широкая категория по этим же
        # номерам отвечает «ноль». Но признаём пустоту только после всех попыток, чтобы
        # разовый сбой не превратился в тихий ноль.
        await _упал(очередь, задача, e, настройки, счёт, наблюдатель, исчерпан="пусто")
        return
    except Exception as e:  # noqa: BLE001 — исход задачи, не обхода
        await _упал(очередь, задача, e, настройки, счёт, наблюдатель)
        return

    страниц_всего = первая.страниц_всего or 1
    докуда = min(страниц_всего, настройки.страниц, ПОТОЛОК_СТРАНИЦ)
    номера = [int(о["номер"]) for о in первая.объявления]
    заметка = None

    for страница in range(2, докуда + 1):
        try:
            ещё = await авито.каталог(ссылка, сортировка=порядок, с_какой=страница,
                                      страниц=1)
        except АдресаКончились:
            raise
        except НеопознаннаяСтраница:
            # Авито завышает число страниц: обещанная страница просто не открывается.
            # Всё, что было до неё, собрано, поэтому это конец выдачи, а не поломка.
            заметка = (f"выдача кончилась на странице {страница}, "
                       f"хотя обещали {страниц_всего}")
            лог.info("артикул %s: %s", задача.артикул, заметка)
            break
        except Exception as e:  # noqa: BLE001 — исход задачи, не обхода
            await _упал(очередь, задача, e, настройки, счёт, наблюдатель)
            return
        номера += [int(о["номер"]) for о in ещё.объявления]
        if len(ещё.объявления) < НА_СТРАНИЦЕ:
            break               # страница неполная — дальше пусто

    # Одно объявление Авито показывает на нескольких страницах, а при сортировке по дате
    # ещё и сдвигает выдачу под нами, поэтому повторы — обычное дело.
    уникальные = list(dict.fromkeys(номера))
    новых = await очередь.поставить_объявления(уникальные)
    широкая = страниц_всего >= ПОТОЛОК_СТРАНИЦ
    await очередь.артикул_готов(задача.артикул, нашлось=первая.всего,
                                страниц=страниц_всего, собрано=len(уникальные),
                                широкая=широкая, заметка=заметка)
    счёт.артикулов += 1
    счёт.объявлений += len(уникальные)
    счёт.новых += новых
    лог.info("артикул %s: найдено %s, собрано %d (новых %d), страниц %d%s",
             задача.артикул, первая.всего, len(уникальные), новых, докуда,
             ", упёрлись в потолок" if широкая else "")


async def _упал(очередь: Очередь, задача: ЗадачаАртикул, ошибка: Exception,
                настройки: Настройки, счёт: Счёт, наблюдатель: Наблюдатель,
                исчерпан: str = "ошибка") -> None:
    статус = await очередь.артикул_упал(задача.артикул,
                                        f"{type(ошибка).__name__}: {ошибка}",
                                        попыток=настройки.попыток, исчерпан=исчерпан)
    if статус == "пусто":
        счёт.пустых += 1
        лог.info("артикул %s: объявлений по номеру нет", задача.артикул)
        наблюдатель.дамп(f"пусто-{задача.артикул}")
        return
    счёт.ошибок += 1
    лог.warning("артикул %s: %s — %s (статус %s)", задача.артикул,
                type(ошибка).__name__, str(ошибка)[:120], статус)
    if статус == "ошибка":
        наблюдатель.дамп(f"артикул-{задача.артикул}")
