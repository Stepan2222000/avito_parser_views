"""Поставщик адресов для библиотеки: она их не ведёт, значит ведём мы.

Как это устроено и почему именно так — по замерам на нашем пуле ProxyElite:

* Адрес выдаётся ровно одному воркеру. Библиотека возвращает адрес только когда с ним
  не сложилось (таймер, капча не решилась, заглушка, молчание), а на успехе продолжает
  ходить с того же — поэтому воркер держит адрес весь свой цикл.
* Получасовой блок и решаемая капча — разные вещи. Капчу библиотека проходит сама и
  адрес при этом не выбывает; выбывает он на таймере, и это блок 403.
* Блок держится около получаса, но через пятнадцать минут свободна уже часть адресов, а
  пробы блокировку не продлевают. Поэтому первую пробу делаем через четверть часа, а если
  адрес всё ещё в блоке — перепроверяем часто. Растить отдых нельзя: это выяснилось
  замером, где отдых, увеличиваемый в полтора раза, за полчаса работы выел столько
  адресов, что темп упал втрое.
* Адрес, который не открывает соединение, отличаем от заблокированного: он отдыхает
  недолго, но после нескольких обрывов подряд выводится из пула, чтобы воркеры не
  тратили на него круги.
"""
from __future__ import annotations

import asyncio
import json
import logging
import time
from pathlib import Path

from curl_cffi import requests as cffi
from curl_cffi.const import CurlOpt

ОТПЕЧАТОК = "firefox133"
ОБРЫВОВ_ДО_ИСКЛЮЧЕНИЯ = 5
БЫСТРЫЕ_ИСХОДЫ = {"прошло"}

# Наш пул ProxyElite слушает TLS: замерено, что через домены на 8443 по схеме https
# отвечают все сто адресов, а те же адреса по http на 8080 четвертью не открываются.
СХЕМА = "https"

лог = logging.getLogger("адреса")


class Адрес:
    """То, что библиотека называет адресом: имя для журнала и сессия с куками."""

    __slots__ = ("имя", "url", "сессия")

    def __init__(self, имя: str, url: str | None):
        self.имя = имя
        self.url = url
        self.сессия = _сессия(url)


def _сессия(url: str | None):
    # Отпечаток TLS обязателен: с ним Авито пускает, без него блокирует. Соединение
    # переиспользовать нельзя — Авито закрывает его после каждого ответа.
    параметры = dict(impersonate=ОТПЕЧАТОК, timeout=30, allow_redirects=True,
                     curl_options={CurlOpt.FRESH_CONNECT: 1, CurlOpt.FORBID_REUSE: 1})
    if url:
        параметры["proxy"] = url
    return cffi.AsyncSession(**параметры)


class Поставщик:
    """Пул адресов с остыванием. Реализует то, что библиотека ждёт от «Адресов»."""

    def __init__(self, файл: Path | str, *, остывание: float = 900.0,
                 проба: float = 300.0, молчание: float = 60.0):
        self.список = прочитать(файл)
        self._остывание = остывание
        self._проба = проба
        self._молчание = молчание
        self._свободен_с: dict[str, float] = {и: 0.0 for и, _ in self.список}
        self._в_блоке: dict[str, int] = {и: 0 for и, _ in self.список}
        self._обрывов: dict[str, int] = {и: 0 for и, _ in self.список}
        self._исключены: set[str] = set()
        self._в_работе: set[str] = set()
        self._живые: dict[str, Адрес] = {}
        self._замок = asyncio.Lock()
        self.исходы: dict[str, int] = {}
        self.ожиданий = 0
        self.ждали = 0.0

    def __len__(self) -> int:
        return len(self.список)

    # ------------------------------------------------------------ то, что зовёт библиотека

    async def взять(self) -> Адрес | None:
        """Свободный адрес. None — только если в пуле не осталось ни одного годного."""
        while True:
            async with self._замок:
                if len(self._исключены) >= len(self.список):
                    return None
                сейчас = time.monotonic()
                ближайшее = None
                for имя, url in self.список:
                    if имя in self._исключены or имя in self._в_работе:
                        continue
                    когда = self._свободен_с[имя]
                    if когда <= сейчас:
                        self._в_работе.add(имя)
                        адрес = Адрес(имя, url)
                        self._живые[имя] = адрес
                        return адрес
                    ближайшее = когда if ближайшее is None else min(ближайшее, когда)
                пауза = 1.0 if ближайшее is None else max(0.5, min(ближайшее - сейчас, 5.0))
            self.ожиданий += 1
            self.ждали += пауза
            if self.ожиданий % 50 == 1:
                лог.warning("свободных адресов нет, ждём: занято %d, отдыхает %d, "
                            "исключено %d", len(self._в_работе), self.отдыхает,
                            len(self._исключены))
            await asyncio.sleep(пауза)

    async def вернуть(self, адрес: Адрес, исход: str) -> None:
        """Библиотека отдаёт адрес, когда с ним не сложилось, и говорит почему."""
        self.исходы[исход] = self.исходы.get(исход, 0) + 1
        async with self._замок:
            self._в_работе.discard(адрес.имя)
            self._живые.pop(адрес.имя, None)
            if исход in БЫСТРЫЕ_ИСХОДЫ:
                self._свободен_с[адрес.имя] = 0.0
                self._в_блоке[адрес.имя] = 0
                self._обрывов[адрес.имя] = 0
            elif исход == "молчит":
                self._обрывов[адрес.имя] += 1
                self._свободен_с[адрес.имя] = time.monotonic() + self._молчание
                if self._обрывов[адрес.имя] >= ОБРЫВОВ_ДО_ИСКЛЮЧЕНИЯ:
                    self._исключены.add(адрес.имя)
                    лог.warning("адрес %s выведен из пула: %d обрывов подряд",
                                адрес.имя, self._обрывов[адрес.имя])
            else:
                # Первый блок — полный отдых, дальше только короткие перепроверки: адрес
                # мог освободиться минуту назад, и ждать его лишние полчаса значит терять
                # рабочие руки на пустом месте.
                подряд = self._в_блоке[адрес.имя]
                отдых = self._остывание if подряд == 0 else self._проба
                self._свободен_с[адрес.имя] = time.monotonic() + отдых
                self._в_блоке[адрес.имя] = подряд + 1
                self._обрывов[адрес.имя] = 0
        await _закрыть(адрес)

    # ------------------------------------------------------------ обслуживание

    async def отпустить(self, адрес: Адрес | None) -> None:
        """Вернуть в пул адрес, с которым всё хорошо: воркер закончил работу."""
        if адрес is None:
            return
        await self.вернуть(адрес, "прошло")

    async def закрыть(self) -> None:
        for адрес in list(self._живые.values()):
            await _закрыть(адрес)
        self._живые.clear()
        self._в_работе.clear()

    @property
    def свободных(self) -> int:
        сейчас = time.monotonic()
        return sum(1 for и, _ in self.список
                   if и not in self._в_работе and и not in self._исключены
                   and self._свободен_с[и] <= сейчас)

    @property
    def отдыхает(self) -> int:
        сейчас = time.monotonic()
        return sum(1 for и, _ in self.список
                   if и not in self._в_работе and и not in self._исключены
                   and self._свободен_с[и] > сейчас)

    def сводка(self) -> dict:
        return {"всего": len(self.список), "в работе": len(self._в_работе),
                "свободно": self.свободных, "отдыхает": self.отдыхает,
                "исключено": len(self._исключены), "исходы": dict(self.исходы),
                "ожиданий": self.ожиданий, "ждали секунд": round(self.ждали)}


async def _закрыть(адрес: Адрес) -> None:
    try:
        закрытие = адрес.сессия.close()
        if закрытие is not None and hasattr(закрытие, "__await__"):
            await закрытие
    except Exception:  # noqa: BLE001 — закрытие сессии не должно ломать обход
        pass


def прочитать(файл: Path | str) -> list[tuple[str, str | None]]:
    """Понимаем два вида списков: строки «хост:порт@логин:пароль» и json от провайдера.

    Строка «напрямую» пригодна для проверок без прокси.
    """
    путь = Path(файл)
    текст = путь.read_text(encoding="utf-8")
    if текст.lstrip().startswith("["):
        return [(п.get("ip") or п["url"], п["url"]) for п in json.loads(текст)]

    список: list[tuple[str, str | None]] = []
    for строка in текст.split():
        строка = строка.strip()
        if not строка or строка.startswith("#"):
            continue
        список.append(_разобрать(строка))
    return список


def _разобрать(строка: str) -> tuple[str, str | None]:
    if строка == "напрямую":
        return "напрямую", None
    if "://" in строка:
        return строка.rsplit("@", 1)[-1].split(":")[0], строка
    if "@" in строка:
        хост, кред = строка.split("@", 1)
        логин, пароль = кред.split(":", 1)
        return хост.split(":")[0], f"{СХЕМА}://{логин}:{пароль}@{хост}"
    части = строка.split(":")
    if len(части) == 4:
        хост, порт, логин, пароль = части
        return хост, f"{СХЕМА}://{логин}:{пароль}@{хост}:{порт}"
    return части[0], f"{СХЕМА}://{строка}"
